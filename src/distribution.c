// Compute logdensity of a dirichlet dist
double
gsl_ran_dirichlet_lnpdf(int K, const double alpha[], const float theta[])
{
  /*We calculate the log of the pdf to minimize the possibility of overflow */
  size_t i;
  double log_p = 0.0;
  double sum_alpha = 0.0;

  for (i = 0; i < K; i++)
  {
    log_p += (alpha[i] - 1.0) * log(theta[i]);
  }

  for (i = 0; i < K; i++)
  {
    sum_alpha += alpha[i];
  }

  log_p += LGammaFF(sum_alpha);

  for (i = 0; i < K; i++)
  {
    log_p -= LGammaFF(alpha[i]);
  }

  return log_p;
}

double
ran_beta(const double a, const double b)
{
  if ((a <= 1.0) && (b <= 1.0))
  {
    double U, V, X, Y;
    while (1)
    {

      U = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
      V = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
      while ((U == 0) || (V == 0))
      {
        U = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
        V = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
      }
      X = pow(U, 1.0 / a);
      Y = pow(V, 1.0 / b);
      if ((X + Y) <= 1.0)
      {
        if (X + Y > 0)
        {
          return X / (X + Y);
        }
        else
        {
          double logX = log(U) / a;
          double logY = log(V) / b;
          double logM = logX > logY ? logX : logY;
          logX -= logM;
          logY -= logM;
          return exp(logX - log(exp(logX) + exp(logY)));
        }
      }
    }
  }
  else
  {
    double x1 = ran_gamma_knuth(a, 1.0);
    double x2 = ran_gamma_knuth(b, 1.0);
    return x1 / (x1 + x2);
  }
}

// ### Generate binomial distribution
unsigned int
ran_binomial(double p, unsigned int n)
{
  unsigned int i, a, b, k = 0;

  while (n > 10) /* This parameter is tunable */
  {
    double X;
    a = 1 + (n / 2);
    b = 1 + n - a;

    X = ran_beta((double)a, (double)b);

    if (X >= p)
    {
      n = a - 1;
      p /= X;
    }
    else
    {
      k += a;
      n = b - 1;
      p = (p - X) / (1 - X);
    }
  }

  for (i = 0; i < n; i++)
  {
    double u = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
    if (u < p)
      k++;
  }

  return k;
}

// ### Generate multinomila distribution
void ran_multinomial(const int K, const unsigned int N, const float p[], int n[])
{

  /* The multinomial distribution has the form

                                    N!           n_1  n_2      n_K
 prob(n_1, n_2, ... n_K) = -------------------- p_1  p_2  ... p_K
                           (n_1! n_2! ... n_K!)

 where n_1, n_2, ... n_K are nonnegative integers, sum_{k=1,K} n_k = N,
 and p = (p_1, p_2, ..., p_K) is a probability distribution.

 Random variates are generated using the conditional binomial method.
 This scales well with N and does not require a setup step.

 Ref:
 C.S. David, The computer generation of multinomial random variates,
 Comp. Stat. Data Anal. 16 (1993) 205-217
*/
  int k;
  double norm = 0.0;
  double sum_p = 0.0;

  unsigned int sum_n = 0;

  /* p[k] may contain non-negative weights that do not sum to 1.0.
   * Even a probability distribution will not exactly sum to 1.0
   * due to rounding errors.
   */

  for (k = 0; k < K; k++)
  {
    norm += p[k];
  }

  for (k = 0; k < K; k++)
  {
    if (p[k] > 0.0)
    {
      n[k] = ran_binomial(p[k] / (norm - sum_p), N - sum_n);
    }
    else
    {
      n[k] = 0;
    }

    sum_p += p[k];
    sum_n += n[k];
  }
}

float GenerateNormal(const float sigma)
{
  // srand(1);
  float x, y, r2;

  do
  {
    /* choose x,y in uniform square (-1,-1) to (+1,+1) */
    x = -1 + 2 * ((double)rand() + 1.) / (1. + (double)RAND_MAX);
    y = -1 + 2 * ((double)rand() + 1.) / (1. + (double)RAND_MAX);
    // printf("X=%2.5f \n",x);
    // printf("Y=%2.5f \n",y);
    /* see if it is in the unit circle */
    r2 = x * x + y * y;
  } while (r2 > 1.0 || r2 == 0);

  /* Box-Muller transform */
  return sigma * y * sqrt(-2.0 * log(r2) / r2);
}

//// Generate from gamma distributions

/* The Gamma distribution of order a>0 is defined by:

   p(x) dx = {1 / \Gamma(a) b^a } x^{a-1} e^{-x/b} dx

   for x>0.  If X and Y are independent gamma-distributed random
   variables of order a1 and a2 with the same scale parameter b, then
   X+Y has gamma distribution of order a1+a2.

   The algorithms below are from Knuth, vol 2, 2nd ed, p. 129. */

static double gamma_large(const double a);
static double gamma_frac(const double a);
double ran_gamma_int(const unsigned int a);
double ran_gamma_knuth(const double a, const double b)
{
  /* assume a > 0 */
  unsigned int na = floor(a);

  if (a >= INT_MAX)
  {
    return b * (gamma_large(floor(a)) + gamma_frac(a - floor(a)));
  }
  else if (a == na)
  {
    return b * ran_gamma_int(na);
  }
  else if (na == 0)
  {
    return b * gamma_frac(a);
  }
  else
  {
    return b * (ran_gamma_int(na) + gamma_frac(a - na));
  }
}

static double
gamma_large(const double a)
{
  // srand(r);
  /* Works only if a > 1, and is most efficient if a is large

   This algorithm, reported in Knuth, is attributed to Ahrens.  A
   faster one, we are told, can be found in: J. H. Ahrens and
   U. Dieter, Computing 12 (1974) 223-246.  */

  double sqa, x, y, v;
  sqa = sqrt(2 * a - 1);
  do
  {
    do
    {
      y = tan(M_PI * ((double)rand() + 1.) / (1. + (double)RAND_MAX));
      x = sqa * y + a - 1;
    } while (x <= 0);
    v = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
  } while (v > (1 + y * y) * exp((a - 1) * log(x / (a - 1)) - sqa * y));

  return x;
}

static double
gamma_frac(const double a)
{
  /* This is exercise 16 from Knuth; see page 135, and the solution is
     on page 551.  */
  // srand(r);
  double p, q, x, u, v;

  if (a == 0)
  {
    return 0;
  }

  p = M_E / (a + M_E);
  do
  {
    u = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
    v = ((double)rand() + 1.) / (1. + (double)RAND_MAX);
    while (v == 0)
      v = ((double)rand() + 1.) / (1. + (double)RAND_MAX);

    if (u < p)
    {
      x = exp((1 / a) * log(v));
      q = exp(-x);
    }
    else
    {
      x = 1 - log(v);
      q = exp((a - 1) * log(x));
    }
  } while (((double)rand() + 1.) / (1. + (double)RAND_MAX) >= q);

  return x;
}

double
ran_gamma_int(const unsigned int a)
{
  // srand(r);
  if (a < 12)
  {
    unsigned int i;
    double prod = 1;

    for (i = 0; i < a; i++)
    {
      prod *= ((double)rand() + 1.) / (1. + (double)RAND_MAX);
    }

    /* Note: for 12 iterations we are safe against underflow, since
       the smallest positive random number is O(2^-32). This means
       the smallest possible product is 2^(-12*32) = 10^-116 which
       is within the range of double precision. */

    return -log(prod);
  }
  else
  {
    return gamma_large((double)a);
  }
}

/* The exponential distribution has the form

   p(x) dx = exp(-x/mu) dx/mu

   for x = 0 ... +infty */

double rexponential(const double mu)
{
  double u = ((double)rand() + 1.) / (1. + (double)RAND_MAX);

  return -mu * log1p(-u);
}

// Generae from truncated normal distribution

/* Exponential rejection sampling (a,inf) */
double ers_a_inf(double a)
{
  // SAMPLER_DEBUG("ers_a_inf", a, R_PosInf);
  const double ainv = 1.0 / a;
  double x, rho;
  do
  {
    // x = rexp(ainv) + a; /* rexp works with 1/lambda */
    x = rexponential(ainv) + a;
    rho = exp(-0.5 * pow((x - a), 2));
  } while (((double)rand() + 1.) / (1. + (double)RAND_MAX) > rho);
  return x;
}

/* Normal rejection sampling (a,inf) */
double nrs_a_inf(double a)
{
  // SAMPLER_DEBUG("nrs_a_inf", a, R_PosInf);
  // double x = -DBL_AX;
  double x = GenerateNormal(1.0);
  // double x = gsl_ran_ugaussian(r);
  while (x < a)
  {
    x = GenerateNormal(1.0);
    // x = gsl_ran_ugaussian(r);
  }
  return x;
}

double r_lefttruncnorm(double a, double mean, double sd)
{
  const double alpha = (a - mean) / sd;
  if (alpha < t4)
  {
    return mean + sd * nrs_a_inf(alpha);
  }
  else
  {
    return mean + sd * ers_a_inf(alpha);
  }
}
double r_righttruncnorm(double b, double mean, double sd)
{
  const double beta = (b - mean) / sd;
  /* Exploit symmetry: */
  return mean - sd * r_lefttruncnorm(-beta, 0.0, 1.0);
}
